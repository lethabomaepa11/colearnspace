	<h2>Cookies and offline storage</h2>
	<p>
		Essential session cookies keep you signed in. We use no advertising or analytics cookies. The
		PWA caches app assets and previously opened anonymous public pages for offline reading. Account
		pages, owner metrics, private token links, Pro actions and signed-in responses are not cached.
		Clear browser site data to remove offline copies. Actions require a connection and are not
		silently queued.
	</p>
